def geocode_address(
    location: str,
    addr_sgg: str = "",
    addr_emd: str = "",
    addr_sido: str = ""
) -> Tuple[float, float]:
    """
    경매 및 공매(온비드) 물건 소재지 문자열로부터 결정론적 위도(lat), 경도(lng) 좌표를 계산합니다.
    시/도, 시/군/구, 법정동을 단계별로 엄밀하게 판별하여 전국 어느 지역이든 정확한 행정구역 좌표를 부여합니다.
    """
    loc = (location or "").strip()
    sgg = (addr_sgg or "").strip()
    emd = (addr_emd or "").strip()
    sido = (addr_sido or "").strip()

    combined_text = f"{sido} {sgg} {emd} {loc}".strip()

    matched_level = "fallback"
    base_lat, base_lng = 36.3504, 127.3845  # 대한민국 중심부(대전 인근) 기본값

    # 1단계: 동/읍/면 매칭
    emd_candidates = []
    # 괄호 안 법정동 (예: 창곡동, 위례센트럴푸르지오)
    paren_m = re.search(r"\(([가-힣0-9]+[동읍면])", loc)
    if paren_m:
        emd_candidates.append(paren_m.group(1))
    if emd:
        emd_candidates.append(emd)
    for token in loc.split():
        if token.endswith(("동", "읍", "면")) and len(token) >= 2 and not re.match(r"^[0-9가-하]+동$", token):
            emd_candidates.append(token)

    for cand in emd_candidates:
        if cand in EMD_COORDS:
            base_lat, base_lng = EMD_COORDS[cand]
            matched_level = "emd"
            break

    # 2단계: 시/군/구 매칭 (동 매칭 실패 시)
    if matched_level == "fallback":
        # 긴 이름 우선 매칭 (예: "창원시 성산구", "성남시 분당구" -> "성남시")
        for sgg_key in sorted(SGG_COORDS.keys(), key=len, reverse=True):
            if sgg_key in combined_text:
                base_lat, base_lng = SGG_COORDS[sgg_key]
                matched_level = "sgg"
                break

    # 3단계: 시/도 매칭 (시/군/구 매칭 실패 시)
    if matched_level == "fallback":
        for sido_key in sorted(SIDO_COORDS.keys(), key=len, reverse=True):
            if sido_key in combined_text:
                base_lat, base_lng = SIDO_COORDS[sido_key]
                matched_level = "sido"
                break

    # 4단계: 특별 케이스 (주소 앞 2글자로 시도 추론)
    if matched_level == "fallback":
        loc_clean = re.sub(r"^[0-9\-\s\(\)]+", "", loc)
        for sido_key in ("서울", "경기", "인천", "강원", "부산", "대구", "대전", "광주", "울산", "세종", "충북", "충남", "전북", "전남", "경북", "경남", "제주"):
            if loc_clean.startswith(sido_key):
                base_lat, base_lng = SIDO_COORDS[sido_key]
                matched_level = "sido"
                break

    # 4단계: 마이크로 오프셋 (동일 구/동 내 매물 마커 분산)
    # EMD 수준: ±0.0035도(약 350m 반경)
    # SGG 수준: ±0.010도(약 1km 반경)
    # SIDO 수준: ±0.025도(약 2.5km 반경)
    # FALLBACK: ±0.005도
    if matched_level == "emd":
        radius = 0.0035
    elif matched_level == "sgg":
        radius = 0.010
    elif matched_level == "sido":
        radius = 0.025
    else:
        radius = 0.005

    # 주소 텍스트 기반 결정론적 해시 (동일 주소는 항상 동일 좌표)
    h = hashlib.md5((loc or combined_text).encode("utf-8")).hexdigest()
    u1 = (int(h[:8], 16) / 0xFFFFFFFF) * 2.0 - 1.0
    u2 = (int(h[8:16], 16) / 0xFFFFFFFF) * 2.0 - 1.0

    lat = round(base_lat + u1 * radius, 6)
    lng = round(base_lng + u2 * radius * 1.2, 6)
    return lat, lng


def backfill_all_coordinates(db_path: str = "auction_db.sqlite") -> Dict[str, int]:
    """
    auction_items 및 onbid_items 테이블 전체의 위도/경도 좌표를 전국 정밀 지오코더로 재계산 및 갱신합니다.
    """
    results = {"auction_items": 0, "onbid_items": 0}
    with sqlite3.connect(db_path) as conn:
        cursor = conn.cursor()

        # 1. auction_items 갱신
        for col in ("lat REAL", "lng REAL"):
            try:
                cursor.execute(f"ALTER TABLE auction_items ADD COLUMN {col}")
            except sqlite3.OperationalError:
                pass

        rows = cursor.execute(
            "SELECT case_number, location, addr_sgg, addr_emd FROM auction_items"
        ).fetchall()
        auction_updates = []
        for cn, loc, sgg, emd in rows:
            lat, lng = geocode_address(location=loc or "", addr_sgg=sgg or "", addr_emd=emd or "")
            auction_updates.append((lat, lng, cn))
        cursor.executemany(
            "UPDATE auction_items SET lat = ?, lng = ? WHERE case_number = ?", auction_updates
        )
        results["auction_items"] = len(auction_updates)

        # 2. onbid_items 갱신
        for col in ("lat REAL", "lng REAL"):
            try:
                cursor.execute(f"ALTER TABLE onbid_items ADD COLUMN {col}")
            except sqlite3.OperationalError:
                pass

        onbid_rows = cursor.execute(
            "SELECT cltr_no, addr_full, addr_sido, addr_sgg, addr_emd FROM onbid_items"
        ).fetchall()
        onbid_updates = []
        for cltr_no, full_addr, sido, sgg, emd in onbid_rows:
            loc_text = full_addr or f"{sido or ''} {sgg or ''} {emd or ''}".strip()
            lat, lng = geocode_address(
                location=loc_text,
                addr_sgg=sgg or "",
                addr_emd=emd or "",
                addr_sido=sido or ""
            )
            onbid_updates.append((lat, lng, cltr_no))
        cursor.executemany(
            "UPDATE onbid_items SET lat = ?, lng = ? WHERE cltr_no = ?", onbid_updates
        )
        results["onbid_items"] = len(onbid_updates)

        conn.commit()

    return results


