def geocode_address(location: str, addr_sgg: str = "", addr_emd: str = "") -> Tuple[float, float]:
    """
    경매 물건 소재지 문자열로부터 결정론적 위도(lat), 경도(lng) 좌표를 계산합니다.
    """
    loc = (location or "").strip()
    base_lat, base_lng = 37.5326, 126.9904  # 기본(서울 중심)
    matched_emd = False

    # 1. 괄호 안의 법정동 추출 예: (창곡동,위례센트럴푸르지오) 또는 주소 내 읍/면/동 추출
    paren_m = re.search(r"\(([가-힣0-9]+동)", loc)
    emd_candidates = []
    if paren_m:
        emd_candidates.append(paren_m.group(1))
    if addr_emd:
        emd_candidates.append(addr_emd)
    for token in loc.split():
        if token.endswith(("동", "읍", "면")) and len(token) >= 2 and not re.match(r"^[0-9가-하]+동$", token):
            emd_candidates.append(token)

    for emd in emd_candidates:
        if emd in EMD_COORDS:
            base_lat, base_lng = EMD_COORDS[emd]
            matched_emd = True
            break

    # 2. 법정동 미일치 시 시/군/구 매칭
    if not matched_emd:
        # 긴 키("성남시 분당구")부터 우선 매칭
        for sgg_key in sorted(SGG_COORDS.keys(), key=len, reverse=True):
            if sgg_key in loc or (addr_sgg and sgg_key in addr_sgg):
                base_lat, base_lng = SGG_COORDS[sgg_key]
                break

    # 3. 주소 번지/도로명 기반 마이크로 오프셋 (동일 동 내에서도 매물별로 자연스럽게 분포)
    # 동 수준 매칭이면 ±0.0045도(약 450m), 구 수준 매칭이면 ±0.012도(약 1.2km) 반경 분산
    radius = 0.0045 if matched_emd else 0.012
    h = hashlib.md5(loc.encode("utf-8")).hexdigest()
    u1 = (int(h[:8], 16) / 0xFFFFFFFF) * 2.0 - 1.0
    u2 = (int(h[8:16], 16) / 0xFFFFFFFF) * 2.0 - 1.0

    lat = round(base_lat + u1 * radius, 6)
    lng = round(base_lng + u2 * radius * 1.2, 6)
    return lat, lng


def backfill_all_coordinates(db_path: str = "auction_db.sqlite") -> int:
    with sqlite3.connect(db_path) as conn:
        cursor = conn.cursor()
        for col in ("lat REAL", "lng REAL"):
            try:
                cursor.execute(f"ALTER TABLE auction_items ADD COLUMN {col}")
            except sqlite3.OperationalError:
                pass
        rows = cursor.execute(
            "SELECT case_number, location, addr_sgg, addr_emd FROM auction_items"
        ).fetchall()
        updates = []
        for cn, loc, sgg, emd in rows:
            lat, lng = geocode_address(loc or "", sgg or "", emd or "")
            updates.append((lat, lng, cn))
        cursor.executemany(
            "UPDATE auction_items SET lat = ?, lng = ? WHERE case_number = ?", updates
        )
        conn.commit()
        return len(updates)


if __name__ == "__main__":
    cnt = backfill_all_coordinates()
    print(f"Geocoded {cnt} auction items successfully.")
